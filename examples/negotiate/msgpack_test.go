// TestMsgpackGeneratedInteroperatesWithReflection checks that tinylib/msgp
// generated methods and the reflection fallback read each other's bytes.
func TestMsgpackGeneratedInteroperatesWithReflection(t *testing.T) {
	codec := msgpackcodec.New()

	type pair struct {
		name      string
		value     any
		plainType reflect.Type
	}
	var pairs []pair
	for _, tt := range edgeTests {
		pairs = append(pairs, pair{"edge/" + tt.name, tt.edge, reflect.TypeFor[plainEdge]()})
	}
	pairs = append(pairs,
		pair{"menu/large", fixtures.LargeMenu(), reflect.TypeFor[plainMenu]()},
		pair{"menu/empty", fixtures.BenchMenu{}, reflect.TypeFor[plainMenu]()},
		pair{"option", fixtures.BenchOption{ID: "a", Name: "b", Price: -3}, reflect.TypeFor[plainOption]()},
	)

	for _, p := range pairs {
		t.Run(p.name, func(t *testing.T) {
			plain := reflect.ValueOf(p.value).Convert(p.plainType).Interface()

			generatedBytes, err := codec.Marshal(p.value, nil, nil)
			if err != nil {
				t.Fatal(err)
			}
			reflectionBytes, err := codec.Marshal(plain, nil, nil)
			if err != nil {
				t.Fatal(err)
			}

			viaGenerated := reflect.New(reflect.TypeOf(p.value))
			err = codec.Unmarshal(reflectionBytes, viaGenerated.Interface(), nil, nil)
			if err != nil {
				t.Fatalf("generated decode of reflection bytes: %v", err)
			}
			viaReflection := reflect.New(p.plainType)
			err = codec.Unmarshal(generatedBytes, viaReflection.Interface(), nil, nil)
			if err != nil {
				t.Fatalf("reflection decode of generated bytes: %v", err)
			}

			for name, got := range map[string]any{
				"generated":  viaGenerated.Elem().Interface(),
				"reflection": viaReflection.Elem().Convert(reflect.TypeOf(p.value)).Interface(),
			} {
				if diff := cmp.Diff(p.value, got, compareOpts); diff != "" {
					t.Errorf("%s decode mismatch (-want +got):\n%s", name, diff)
				}
			}
		})
	}
}

func TestMsgpackRejectsBadInput(t *testing.T) {
	codec := msgpackcodec.New()
	valid, err := codec.Marshal(fixtures.Edge{Names: []string{"a"}, Negative: 5}, nil, nil)
	if err != nil {
		t.Fatal(err)
	}

	tests := []struct {
		name string
		data []byte
	}{
		{"garbage", []byte("\xc1\xc1\xc1garbage")},
		{"scalar for struct", []byte{0x01}},
		{"string for array", []byte{0x81, 0xa5, 'n', 'a', 'm', 'e', 's', 0xa1, 'x'}},
		{"array for number", []byte{0x81, 0xa8, 'n', 'e', 'g', 'a', 't', 'i', 'v', 'e', 0x91, 0x01}},
	}
	for length := 1; length < len(valid); length++ {
		tests = append(tests, struct {
			name string
			data []byte
		}{"truncated", valid[:length]})
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var generated fixtures.Edge
			var reflected plainEdge
			generatedErr := codec.Unmarshal(tt.data, &generated, nil, nil)
			reflectedErr := codec.Unmarshal(tt.data, &reflected, nil, nil)
			if generatedErr == nil || reflectedErr == nil {
				t.Errorf("want errors from both paths, got generated=%v reflection=%v", generatedErr, reflectedErr)
			}
		})
	}
}
