// Package protogen generates reflection-free protobuf encoders and decoders
// for Go structs. The JTD schema decides field numbers and wire shapes through
// protocodec.Compile, the same plan the reflection codec runs; the struct only
// supplies Go field access. Generated types implement protocodec.Marshaler and
// protocodec.Unmarshaler, so a schema mismatch falls back to reflection.
//
// Unsupported (reported as errors): map keys that are not string kinds,
// embedded pointers on a promoted field's path, anonymous struct types and
// arrays.
package protogen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"maps"
	"path"
	"reflect"
	"regexp"
	"slices"
	"strings"

	"github.com/LOKE/pkg/examples/negotiate/protocodec"
	jtd "github.com/jsontypedef/json-typedef-go"
	"google.golang.org/protobuf/encoding/protowire"
)

// Root is a struct type that gets MarshalProto, UnmarshalProto and
// ProtoFingerprint methods, generated for Schema.
type Root struct {
	Type   reflect.Type
	Schema jtd.Schema
}

// Config describes one generated file. Roots must be named struct types
// declared in PkgPath.
type Config struct {
	PkgName string
	PkgPath string
	Command string
	Roots   []Root
	Defs    map[string]jtd.Schema
}

var stdImports = map[string]string{
	"fmt":                                    "fmt",
	"math":                                   "math",
	"maps":                                   "maps",
	"slices":                                 "slices",
	"sync/atomic":                            "atomic",
	"encoding/json":                          "json",
	"github.com/jsontypedef/json-typedef-go": "jtd",
	"google.golang.org/protobuf/encoding/protowire":     "protowire",
	"github.com/LOKE/pkg/examples/negotiate/codecutil":  "codecutil",
	"github.com/LOKE/pkg/examples/negotiate/protocodec": "protocodec",
}

type generator struct {
	cfg     Config
	body    bytes.Buffer
	types   map[string]string
	aliases map[string]string
	structs map[*protocodec.Node]int
	queue   []*protocodec.Node
	counter int
	err     error
}

// Generate returns the gofmt'd source for cfg. Schemas are round-tripped
// through JSON first so they match what clients read from the service meta.
func Generate(cfg Config) ([]byte, error) {
	var err error
	cfg.Defs, err = roundTrip(cfg.Defs)
	if err != nil {
		return nil, err
	}

	g := &generator{
		cfg:     cfg,
		types:   map[string]string{},
		aliases: map[string]string{},
		structs: map[*protocodec.Node]int{},
	}
	for importPath, alias := range stdImports {
		g.aliases[alias] = importPath
	}

	for _, root := range cfg.Roots {
		schema, err := roundTrip(root.Schema)
		if err != nil {
			return nil, err
		}
		err = g.root(root.Type, &schema)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", root.Type, err)
		}
	}

	for len(g.queue) > 0 && g.err == nil {
		node := g.queue[0]
		g.queue = g.queue[1:]
		g.putFunc(node)
		g.readFunc(node)
	}
	if g.err != nil {
		return nil, g.err
	}

	return g.file()
}

func roundTrip[T any](value T) (T, error) {
	var out T
	encoded, err := json.Marshal(value)
	if err != nil {
		return out, err
	}
	err = json.Unmarshal(encoded, &out)
	return out, err
}

func (g *generator) fail(format string, args ...any) {
	if g.err == nil {
		g.err = fmt.Errorf(format, args...)
	}
}

func (g *generator) p(format string, args ...any) {
	fmt.Fprintf(&g.body, format+"\n", args...)
}

func (g *generator) name(prefix string) string {
	g.counter++
	return fmt.Sprintf("%s%d", prefix, g.counter)
}

func (g *generator) file() ([]byte, error) {
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by %s. DO NOT EDIT.\n\npackage %s\n\nimport (\n", g.cfg.Command, g.cfg.PkgName)

	body := g.body.String()
	imports := map[string]string{}
	for importPath, alias := range stdImports {
		if regexp.MustCompile(`\b` + alias + `\.`).MatchString(body) {
			imports[importPath] = alias
		}
	}
	maps.Copy(imports, g.types)
	for _, importPath := range slices.Sorted(maps.Keys(imports)) {
		if imports[importPath] == path.Base(importPath) {
			fmt.Fprintf(&out, "\t%q\n", importPath)
			continue
		}
		fmt.Fprintf(&out, "\t%s %q\n", imports[importPath], importPath)
	}
	out.WriteString(")\n\n")
	out.WriteString(body)

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting generated code: %w\n%s", err, out.String())
	}
	return formatted, nil
}

func (g *generator) typeName(t reflect.Type) string {
	if t.Name() != "" {
		if t.PkgPath() == "" {
			return t.Name()
		}
		if strings.ContainsAny(t.Name(), "[]") {
			g.fail("generic type %s is not supported", t)
			return "invalid"
		}
		if t.PkgPath() == g.cfg.PkgPath {
			return t.Name()
		}
		return g.alias(t.PkgPath()) + "." + t.Name()
	}

	switch t.Kind() {
	case reflect.Pointer:
		return "*" + g.typeName(t.Elem())
	case reflect.Slice:
		return "[]" + g.typeName(t.Elem())
	case reflect.Map:
		return "map[" + g.typeName(t.Key()) + "]" + g.typeName(t.Elem())
	case reflect.Interface:
		if t.NumMethod() == 0 {
			return "any"
		}
	}
	g.fail("unsupported type %s", t)
	return "invalid"
}

func (g *generator) alias(importPath string) string {
	if alias, ok := stdImports[importPath]; ok {
		g.types[importPath] = alias
		return alias
	}
	if alias, ok := g.types[importPath]; ok {
		return alias
	}

	alias := path.Base(importPath)
	for g.aliases[alias] != "" && g.aliases[alias] != importPath {
		alias += "x"
	}
	g.aliases[alias] = importPath
	g.types[importPath] = alias
	return alias
}

func (g *generator) structID(node *protocodec.Node) int {
	id, ok := g.structs[node]
	if !ok {
		id = len(g.structs) + 1
		g.structs[node] = id
		g.queue = append(g.queue, node)
	}
	return id
}

func (g *generator) root(t reflect.Type, schema *jtd.Schema) error {
	if t.Kind() != reflect.Struct || t.Name() == "" || t.PkgPath() != g.cfg.PkgPath {
		return fmt.Errorf("root must be a named struct declared in %s", g.cfg.PkgPath)
	}
	node, err := protocodec.Compile(schema, t, g.cfg.Defs)
	if err != nil {
		return err
	}
	fingerprint, err := protocodec.Fingerprint(schema, g.cfg.Defs)
	if err != nil {
		return err
	}

	id := g.structID(node)
	name := t.Name()
	g.p("func (v %s) ProtoFingerprint() string { return %q }", name, fingerprint)
	g.p(`// protoSizeHint%[1]s remembers the last message size to presize the next buffer.
	var protoSizeHint%[1]s atomic.Int64

	func (v %[1]s) MarshalProto() ([]byte, error) {
		w := protocodec.NewWriter(int(protoSizeHint%[1]s.Load()))
		mark := w.Len()
		err := put%[2]d(w, &v)
		if err != nil {
			return nil, err
		}
		w.PrependLength(mark)
		w.PrependTag(1, protowire.BytesType)
		protoSizeHint%[1]s.Store(int64(w.Len()))
		return w.Bytes(), nil
	}`, name, id)
	g.p(`func (v *%s) UnmarshalProto(data []byte) error {
		for len(data) > 0 {
			num, wt, tagLen := protowire.ConsumeTag(data)
			if tagLen < 0 {
				return protowire.ParseError(tagLen)
			}
			data = data[tagLen:]
			var used int
			if num != 1 {
				used = protowire.ConsumeFieldValue(num, wt, data)
				if used < 0 {
					return protowire.ParseError(used)
				}
				data = data[used:]
				continue
			}
			if wt != protowire.BytesType {
				return fmt.Errorf("wire type %%d, want %%d", wt, protowire.BytesType)
			}
			body, used := protowire.ConsumeBytes(data)
			if used < 0 {
				return protowire.ParseError(used)
			}
			err := read%d(body, v)
			if err != nil {
				return err
			}
			data = data[used:]
		}
		return nil
	}`, name, id)
	return nil
}

// fieldAccess returns the Go expression reaching field from variable v.
func (g *generator) fieldAccess(structType reflect.Type, field []int) (string, reflect.Type) {
	expr := "v"
	t := structType
	for i, index := range field {
		sf := t.Field(index)
		expr += "." + sf.Name
		t = sf.Type
		if t.Kind() == reflect.Pointer && i < len(field)-1 {
			g.fail("%s: promoted field through embedded pointer %s is not supported", structType, sf.Name)
		}
	}
	return expr, t
}

func (g *generator) putFunc(node *protocodec.Node) {
	id := g.structs[node]
	t := node.GoType
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}

	g.p("func put%d(w *protocodec.Writer, v *%s) (err error) {", id, g.typeName(t))
	g.p("var field string")
	g.p(`defer func() {
		if err != nil {
			err = fmt.Errorf("%%s: %%w", field, err)
		}
	}()`)
	for _, plan := range slices.Backward(node.Fields) {
		if plan.Field == nil {
			continue
		}
		expr, fieldType := g.fieldAccess(t, plan.Field.Index)
		g.p("field = %q", plan.Name)
		g.encField(plan.Node, expr, fieldType, plan.Num)
	}
	g.p("return nil\n}\n")
}

func wireType(n *protocodec.Node) string {
	switch n.Kind {
	case protocodec.KindBool, protocodec.KindInt, protocodec.KindUint:
		return "protowire.VarintType"
	case protocodec.KindFloat32:
		return "protowire.Fixed32Type"
	case protocodec.KindFloat64:
		return "protowire.Fixed64Type"
	}
	return "protowire.BytesType"
}

func (g *generator) encField(n *protocodec.Node, e string, t reflect.Type, num protowire.Number) {
	closers := 0
	explicit := false
	if n.Kind != protocodec.KindJSON {
		for t.Kind() == reflect.Pointer {
			g.p("if %s != nil {", e)
			closers++
			e = "(*" + e + ")"
			t = t.Elem()
			explicit = true
		}
	}

	switch n.Kind {
	case protocodec.KindList:
		g.encList(n, e, t, num)
	case protocodec.KindMap:
		g.encMap(n, e, t, num)
	case protocodec.KindJSON:
		switch t.Kind() {
		case reflect.Interface, reflect.Pointer, reflect.Map, reflect.Slice:
			g.p("if %s != nil {", e)
			closers++
		}
		data := g.name("data")
		g.p("%s, err := json.Marshal(%s)", data, e)
		g.p("if err != nil {\nreturn err\n}")
		g.p("w.PrependBytes(%s)", data)
		g.p("w.PrependVarint(uint64(len(%s)))", data)
		g.p("w.PrependTag(%d, protowire.BytesType)", num)
	default:
		omitUnless := ""
		if !explicit {
			omitUnless = nonZero(n, e)
		}
		if n.Kind == protocodec.KindTimestamp {
			g.alias("time")
		}
		if omitUnless != "" {
			g.p("if %s {", omitUnless)
			closers++
		}
		g.encPayload(n, e, t)
		g.p("w.PrependTag(%d, %s)", num, wireType(n))
	}

	for range closers {
		g.p("}")
	}
}

// nonZero is the condition under which an unwrapped scalar is written,
// matching reflect's IsZero so output is byte-identical to the reflection codec.
func nonZero(n *protocodec.Node, e string) string {
	switch n.Kind {
	case protocodec.KindBool:
		return e
	case protocodec.KindInt, protocodec.KindUint:
		return e + " != 0"
	case protocodec.KindFloat32, protocodec.KindFloat64:
		return "math.Float64bits(float64(" + e + ")) != 0"
	case protocodec.KindString:
		return e + ` != ""`
	case protocodec.KindTimestamp:
		return e + " != (time.Time{})"
	}
	return ""
}

func isUnsigned(t reflect.Type) bool {
	switch t.Kind() {
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return true
	}
	return false
}

// encPayload writes the value of n, without its tag, at the front.
func (g *generator) encPayload(n *protocodec.Node, e string, t reflect.Type) {
	g.p("{")
	defer g.p("}")

	switch n.Kind {
	case protocodec.KindBool:
		g.p("w.PrependVarint(protowire.EncodeBool(bool(%s)))", e)
	case protocodec.KindInt, protocodec.KindUint:
		x := g.name("x")
		if isUnsigned(t) {
			g.p("if uint64(%s) > math.MaxInt64 {\nreturn fmt.Errorf(\"value %%d out of range for %%s\", uint64(%s), %q)\n}", e, e, n.SchemaType)
		}
		g.p("%s := int64(%s)", x, e)
		g.p("err := codecutil.CheckInt(%s, jtd.Type(%q))\nif err != nil {\nreturn err\n}", x, n.SchemaType)
		if n.Kind == protocodec.KindInt {
			g.p("w.PrependVarint(protowire.EncodeZigZag(%s))", x)
			return
		}
		g.p("w.PrependVarint(uint64(%s))", x)
	case protocodec.KindFloat32:
		g.p("w.PrependFixed32(math.Float32bits(float32(%s)))", e)
	case protocodec.KindFloat64:
		g.p("w.PrependFixed64(math.Float64bits(float64(%s)))", e)
	case protocodec.KindString:
		g.p("w.PrependString(string(%s))", e)
		g.p("w.PrependVarint(uint64(len(%s)))", e)
	case protocodec.KindText:
		text := g.name("text")
		g.p("%s, err := (&%s).MarshalText()\nif err != nil {\nreturn err\n}", text, e)
		g.p("w.PrependBytes(%s)", text)
		g.p("w.PrependVarint(uint64(len(%s)))", text)
	case protocodec.KindTimestamp:
		g.p("w.PrependTimestamp(%s)", e)
	case protocodec.KindStruct:
		mark := g.name("mark")
		g.p("%s := w.Len()", mark)
		g.p("err := put%d(w, &%s)\nif err != nil {\nreturn err\n}", g.structID(n), e)
		g.p("w.PrependLength(%s)", mark)
	default:
		g.fail("no scalar payload for kind %d", n.Kind)
	}
}

// derefElement unwraps pointer elements of a non-nullable list, failing on nil.
func (g *generator) derefElement(e string, t reflect.Type) (string, reflect.Type) {
	for t.Kind() == reflect.Pointer {
		g.p("if %s == nil {\nreturn fmt.Errorf(\"nil element in non-nullable list\")\n}", e)
		e = "(*" + e + ")"
		t = t.Elem()
	}
	return e, t
}

func (g *generator) encList(n *protocodec.Node, e string, t reflect.Type, num protowire.Number) {
	if t.Kind() != reflect.Slice {
		g.fail("list node on %s", t)
		return
	}
	i := g.name("i")
	g.p("if len(%s) > 0 {", e)
	defer g.p("}")

	element := fmt.Sprintf("%s[%s]", e, i)
	if n.Packed {
		mark := g.name("mark")
		g.p("%s := w.Len()", mark)
		g.p("for %s := range slices.Backward(%s) {", i, e)
		elementExpr, elementType := g.derefElement(element, t.Elem())
		g.encPayload(n.Elem, elementExpr, elementType)
		g.p("}")
		g.p("w.PrependLength(%s)", mark)
		g.p("w.PrependTag(%d, protowire.BytesType)", num)
		return
	}

	g.p("for %s := range slices.Backward(%s) {", i, e)
	defer g.p("}")
	if n.WrapElem {
		mark := g.name("mark")
		g.p("%s := w.Len()", mark)
		g.encField(n.Elem, element, t.Elem(), 1)
		g.p("w.PrependLength(%s)", mark)
		g.p("w.PrependTag(%d, protowire.BytesType)", num)
		return
	}
	elementExpr, elementType := g.derefElement(element, t.Elem())
	g.encPayload(n.Elem, elementExpr, elementType)
	g.p("w.PrependTag(%d, %s)", num, wireType(n.Elem))
}

func (g *generator) encMap(n *protocodec.Node, e string, t reflect.Type, num protowire.Number) {
	if t.Kind() != reflect.Map || t.Key().Kind() != reflect.String {
		g.fail("map type %s: only string-kind keys are supported", t)
		return
	}
	keys, i, key, value, mark := g.name("keys"), g.name("i"), g.name("key"), g.name("value"), g.name("mark")

	g.p("if len(%s) > 0 {", e)
	g.p("%s := slices.Sorted(maps.Keys(%s))", keys, e)
	g.p("for %s := range slices.Backward(%s) {", i, keys)
	g.p("%s := %s[%s]", key, keys, i)
	g.p("%s := %s[%s]", value, e, key)
	g.p("%s := w.Len()", mark)
	if n.WrapElem {
		inner := g.name("mark")
		g.p("%s := w.Len()", inner)
		g.encField(n.Elem, value, t.Elem(), 1)
		g.p("w.PrependLength(%s)", inner)
		g.p("w.PrependTag(2, protowire.BytesType)")
	} else {
		g.encField(n.Elem, value, t.Elem(), 2)
	}
	g.encField(n.Key, key, t.Key(), 1)
	g.p("w.PrependLength(%s)", mark)
	g.p("w.PrependTag(%d, protowire.BytesType)", num)
	g.p("}\n}")
}

func (g *generator) readFunc(node *protocodec.Node) {
	id := g.structs[node]
	t := node.GoType
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}

	g.p("func read%d(b []byte, v *%s) (err error) {", id, g.typeName(t))
	g.p("var field string")
	g.p(`defer func() {
		if err != nil {
			err = fmt.Errorf("%%s: %%w", field, err)
		}
	}()`)
	g.p(`for len(b) > 0 {
		num, wt, tagLen := protowire.ConsumeTag(b)
		if tagLen < 0 {
			return protowire.ParseError(tagLen)
		}
		b = b[tagLen:]
		var used int
		switch num {`)
	for _, plan := range node.Fields {
		if plan.Field == nil {
			continue
		}
		expr, fieldType := g.fieldAccess(t, plan.Field.Index)
		g.p("case %d:", plan.Num)
		g.p("field = %q", plan.Name)
		g.readField(plan.Node, expr, fieldType, "b", "wt", "used")
	}
	g.p(`default:
			used = protowire.ConsumeFieldValue(num, wt, b)
			if used < 0 {
				return protowire.ParseError(used)
			}
		}
		b = b[used:]
	}
	return nil
}
`)
}

// allocate makes sure pointer layers around dst exist and returns the value.
func (g *generator) allocate(dst string, t reflect.Type) (string, reflect.Type) {
	for t.Kind() == reflect.Pointer {
		g.p("if %s == nil {\n%s = new(%s)\n}", dst, dst, g.typeName(t.Elem()))
		dst = "(*" + dst + ")"
		t = t.Elem()
	}
	return dst, t
}

// readField decodes one occurrence from b (positioned after the tag, with wire
// type wt) into dst and stores the bytes consumed in used.
func (g *generator) readField(n *protocodec.Node, dst string, t reflect.Type, b, wt, used string) {
	g.p("{")
	defer g.p("}")

	if n.Kind != protocodec.KindJSON {
		dst, t = g.allocate(dst, t)
	}
	switch n.Kind {
	case protocodec.KindList:
		g.readListItem(n, dst, t, b, wt, used)
	case protocodec.KindMap:
		g.readMapEntry(n, dst, t, b, wt, used)
	default:
		g.readPayload(n, dst, t, b, wt, used)
	}
}

func (g *generator) expectWire(n *protocodec.Node, wt string) {
	g.p("if %s != %s {\nreturn fmt.Errorf(\"wire type %%d, want %%d\", %s, %s)\n}", wt, wireType(n), wt, wireType(n))
}

func (g *generator) readPayload(n *protocodec.Node, dst string, t reflect.Type, b, wt, used string) {
	g.expectWire(n, wt)
	raw, size, body := g.name("raw"), g.name("size"), g.name("body")

	switch n.Kind {
	case protocodec.KindBool, protocodec.KindInt, protocodec.KindUint:
		g.p("%s, %s := protowire.ConsumeVarint(%s)\nif %s < 0 {\nreturn protowire.ParseError(%s)\n}\n%s = %s", raw, size, b, size, size, used, size)
		switch n.Kind {
		case protocodec.KindBool:
			g.p("%s = %s != 0", dst, raw)
		case protocodec.KindInt:
			g.setInt(dst, t, "protowire.DecodeZigZag("+raw+")")
		default:
			g.p("if %s > math.MaxInt64 {\nreturn fmt.Errorf(\"value %%d out of range\", %s)\n}", raw, raw)
			g.setInt(dst, t, "int64("+raw+")")
		}
	case protocodec.KindFloat32:
		g.p("%s, %s := protowire.ConsumeFixed32(%s)\nif %s < 0 {\nreturn protowire.ParseError(%s)\n}\n%s = %s", raw, size, b, size, size, used, size)
		g.p("%s = %s(math.Float32frombits(%s))", dst, g.typeName(t), raw)
	case protocodec.KindFloat64:
		g.p("%s, %s := protowire.ConsumeFixed64(%s)\nif %s < 0 {\nreturn protowire.ParseError(%s)\n}\n%s = %s", raw, size, b, size, size, used, size)
		f := g.name("f")
		g.p("%s := math.Float64frombits(%s)", f, raw)
		if t.Kind() == reflect.Float32 {
			abs := g.name("abs")
			g.p("%s := math.Abs(%s)\nif math.MaxFloat32 < %s && %s <= math.MaxFloat64 {\nreturn fmt.Errorf(\"value %%g overflows float32\", %s)\n}", abs, f, abs, abs, f)
		}
		g.p("%s = %s(%s)", dst, g.typeName(t), f)
	default:
		g.p("%s, %s := protowire.ConsumeBytes(%s)\nif %s < 0 {\nreturn protowire.ParseError(%s)\n}\n%s = %s", body, size, b, size, size, used, size)
		g.readBytes(n, dst, t, body)
	}
}

func (g *generator) readBytes(n *protocodec.Node, dst string, t reflect.Type, body string) {
	switch n.Kind {
	case protocodec.KindString:
		g.p("%s = %s(string(%s))", dst, g.typeName(t), body)
	case protocodec.KindText:
		g.p("err := (&%s).UnmarshalText(%s)\nif err != nil {\nreturn err\n}", dst, body)
	case protocodec.KindTimestamp:
		moment := g.name("moment")
		g.p("%s, err := protocodec.ConsumeTimestamp(%s)\nif err != nil {\nreturn err\n}\n%s = %s", moment, body, dst, moment)
	case protocodec.KindStruct:
		g.p("err := read%d(%s, &%s)\nif err != nil {\nreturn err\n}", g.structID(n), body, dst)
	case protocodec.KindJSON:
		g.p("err := json.Unmarshal(%s, &%s)\nif err != nil {\nreturn err\n}", body, dst)
	default:
		g.fail("no bytes payload for kind %d", n.Kind)
	}
}

// setInt stores the int64 expression x into dst, rejecting values that
// overflow the Go integer type.
func (g *generator) setInt(dst string, t reflect.Type, x string) {
	value := g.name("value")
	g.p("%s := %s", value, x)

	var low, high string
	switch t.Kind() {
	case reflect.Int8:
		low, high = "math.MinInt8", "math.MaxInt8"
	case reflect.Int16:
		low, high = "math.MinInt16", "math.MaxInt16"
	case reflect.Int32:
		low, high = "math.MinInt32", "math.MaxInt32"
	case reflect.Uint8:
		low, high = "0", "math.MaxUint8"
	case reflect.Uint16:
		low, high = "0", "math.MaxUint16"
	case reflect.Uint32:
		low, high = "0", "math.MaxUint32"
	case reflect.Uint, reflect.Uint64:
		low = "0"
	}
	switch {
	case low != "" && high != "":
		g.p("if %s < %s || %s > %s {\nreturn fmt.Errorf(\"value %%d overflows %s\", %s)\n}", value, low, value, high, t, value)
	case low != "":
		g.p("if %s < %s {\nreturn fmt.Errorf(\"value %%d overflows %s\", %s)\n}", value, low, t, value)
	}
	g.p("%s = %s(%s)", dst, g.typeName(t), value)
}

func (g *generator) readListItem(n *protocodec.Node, dst string, t reflect.Type, b, wt, used string) {
	if t.Kind() != reflect.Slice {
		g.fail("list node on %s", t)
		return
	}
	elemType := g.typeName(t.Elem())

	appendSlot := func() string {
		slot, zero := g.name("slot"), g.name("zero")
		g.p("var %s %s\n%s = append(%s, %s)\n%s := &%s[len(%s)-1]", zero, elemType, dst, dst, zero, slot, dst, dst)
		return "(*" + slot + ")"
	}

	if n.Packed {
		packed, size, read := g.name("packed"), g.name("size"), g.name("read")
		g.p("if %s == protowire.BytesType {", wt)
		g.p("%s, %s := protowire.ConsumeBytes(%s)\nif %s < 0 {\nreturn protowire.ParseError(%s)\n}\n%s = %s", packed, size, b, size, size, used, size)
		g.p("for len(%s) > 0 {", packed)
		slot := appendSlot()
		g.p("var %s int", read)
		g.readField(n.Elem, slot, t.Elem(), packed, wireType(n.Elem), read)
		g.p("%s = %s[%s:]\n}", packed, packed, read)
		g.p("} else {")
		slot = appendSlot()
		g.readField(n.Elem, slot, t.Elem(), b, wt, used)
		g.p("}")
		return
	}

	slot := appendSlot()
	if !n.WrapElem {
		g.readField(n.Elem, slot, t.Elem(), b, wt, used)
		return
	}
	g.readWrapper(n.Elem, slot, t.Elem(), b, wt, used)
}

// readWrapper decodes a {1: value} message into dst.
func (g *generator) readWrapper(elem *protocodec.Node, dst string, t reflect.Type, b, wt, used string) {
	wrapper, size, num, innerWT, tagLen, innerUsed := g.name("wrapper"), g.name("size"), g.name("num"), g.name("wt"), g.name("tagLen"), g.name("used")

	g.p("if %s != protowire.BytesType {\nreturn fmt.Errorf(\"wire type %%d, want %%d\", %s, protowire.BytesType)\n}", wt, wt)
	g.p("%s, %s := protowire.ConsumeBytes(%s)\nif %s < 0 {\nreturn protowire.ParseError(%s)\n}\n%s = %s", wrapper, size, b, size, size, used, size)
	g.p("for len(%s) > 0 {", wrapper)
	g.p("%s, %s, %s := protowire.ConsumeTag(%s)\nif %s < 0 {\nreturn protowire.ParseError(%s)\n}\n%s = %s[%s:]", num, innerWT, tagLen, wrapper, tagLen, tagLen, wrapper, wrapper, tagLen)
	g.p("var %s int\nif %s == 1 {", innerUsed, num)
	g.readField(elem, dst, t, wrapper, innerWT, innerUsed)
	g.p("} else {\n%s = protowire.ConsumeFieldValue(%s, %s, %s)\nif %s < 0 {\nreturn protowire.ParseError(%s)\n}\n}", innerUsed, num, innerWT, wrapper, innerUsed, innerUsed)
	g.p("%s = %s[%s:]\n}", wrapper, wrapper, innerUsed)
}

func (g *generator) readMapEntry(n *protocodec.Node, dst string, t reflect.Type, b, wt, used string) {
	if t.Kind() != reflect.Map || t.Key().Kind() != reflect.String {
		g.fail("map type %s: only string-kind keys are supported", t)
		return
	}
	entry, size, key, value := g.name("entry"), g.name("size"), g.name("key"), g.name("value")
	num, innerWT, tagLen, innerUsed := g.name("num"), g.name("wt"), g.name("tagLen"), g.name("used")

	g.p("if %s != protowire.BytesType {\nreturn fmt.Errorf(\"wire type %%d, want %%d\", %s, protowire.BytesType)\n}", wt, wt)
	g.p("%s, %s := protowire.ConsumeBytes(%s)\nif %s < 0 {\nreturn protowire.ParseError(%s)\n}\n%s = %s", entry, size, b, size, size, used, size)
	g.p("if %s == nil {\n%s = make(%s)\n}", dst, dst, g.typeName(t))
	g.p("var %s %s\nvar %s %s", key, g.typeName(t.Key()), value, g.typeName(t.Elem()))
	g.p("for len(%s) > 0 {", entry)
	g.p("%s, %s, %s := protowire.ConsumeTag(%s)\nif %s < 0 {\nreturn protowire.ParseError(%s)\n}\n%s = %s[%s:]", num, innerWT, tagLen, entry, tagLen, tagLen, entry, entry, tagLen)
	g.p("var %s int\nswitch %s {\ncase 1:", innerUsed, num)
	g.readField(n.Key, key, t.Key(), entry, innerWT, innerUsed)
	g.p("case 2:")
	if n.WrapElem {
		g.readWrapper(n.Elem, value, t.Elem(), entry, innerWT, innerUsed)
	} else {
		g.readField(n.Elem, value, t.Elem(), entry, innerWT, innerUsed)
	}
	g.p("default:\n%s = protowire.ConsumeFieldValue(%s, %s, %s)\nif %s < 0 {\nreturn protowire.ParseError(%s)\n}\n}", innerUsed, num, innerWT, entry, innerUsed, innerUsed)
	g.p("%s = %s[%s:]\n}", entry, entry, innerUsed)
	g.p("%s[%s] = %s", dst, key, value)
}
